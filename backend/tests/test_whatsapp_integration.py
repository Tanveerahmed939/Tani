# ---------- GET /api/settings never leaks secrets ----------

class TestSettingsMasking:
    def test_get_settings_never_returns_raw_secrets(self, api_client, base_url, auth_headers):
        r = api_client.get(f"{base_url}/api/settings", headers=auth_headers, timeout=15)
        assert r.status_code == 200, r.text
        data = r.json()
        # Must never return the raw fields
        assert "whatsapp_access_token" not in data
        assert "whatsapp_app_secret" not in data
        # Must return the *_set booleans
        assert "whatsapp_access_token_set" in data
        assert "whatsapp_app_secret_set" in data

    def test_patch_settings_saves_wa_and_returns_masked(self, api_client, base_url, auth_headers):
        body = {
            "whatsapp_enabled": True,
            "whatsapp_access_token": FAKE_TOKEN,
            "whatsapp_phone_number_id": FAKE_PHONE_ID,
            "whatsapp_app_secret": FAKE_APP_SECRET,
            "owner_whatsapp_number": FAKE_OWNER,
        }
        r = api_client.patch(f"{base_url}/api/settings", json=body, headers=auth_headers, timeout=15)
        assert r.status_code == 200, r.text
        data = r.json()
        # No raw secrets in response
        assert "whatsapp_access_token" not in data
        assert "whatsapp_app_secret" not in data
        # Masked fields present
        assert data.get("whatsapp_access_token_set") is True
        assert data.get("whatsapp_app_secret_set") is True
        assert data.get("whatsapp_access_token_masked", "").startswith("EAA")
        # Non-sensitive fields echoed
        assert data.get("owner_whatsapp_number") == FAKE_OWNER
        assert data.get("whatsapp_phone_number_id") == FAKE_PHONE_ID
        assert data.get("whatsapp_enabled") is True

    def test_verify_token_autogenerated(self, api_client, base_url, auth_headers):
        r = api_client.get(f"{base_url}/api/settings/whatsapp", headers=auth_headers, timeout=15)
        assert r.status_code == 200, r.text
        data = r.json()
        assert data.get("verify_token"), "verify_token should be auto-generated after WA save"
        webhook_url = data.get("webhook_url", "")
        assert webhook_url.endswith("/api/whatsapp/webhook")
        # Regression (iter 3 bug): must be public HTTPS URL, not internal K8s host over http
        assert webhook_url.startswith("https://"), f"webhook_url must be HTTPS, got {webhook_url}"
        # Must be the public preview domain from PUBLIC_BASE_URL env
        import os as _os
        from dotenv import load_dotenv as _ld
        from pathlib import Path as _P
        _ld(_P("/app/backend/.env"))
        public_base = _os.environ.get("PUBLIC_BASE_URL", "").rstrip("/")
        assert public_base, "PUBLIC_BASE_URL must be set in /app/backend/.env"
        assert webhook_url == f"{public_base}/api/whatsapp/webhook", (
            f"webhook_url {webhook_url} does not match expected {public_base}/api/whatsapp/webhook"
        )
        assert data.get("whatsapp_enabled") is True
        assert data.get("access_token_set") is True
        assert data.get("app_secret_set") is True
        assert data.get("phone_number_id") == FAKE_PHONE_ID
        assert data.get("owner_whatsapp_number") == FAKE_OWNER


# ---------- Webhook verify (GET) ----------

class TestWebhookVerify:
    def _current_verify_token(self, api_client, base_url, auth_headers):
        r = api_client.get(f"{base_url}/api/settings/whatsapp", headers=auth_headers, timeout=15)
        assert r.status_code == 200
        return r.json()["verify_token"]

    def test_webhook_verify_correct_token_returns_challenge(self, api_client, base_url, auth_headers):
        vt = self._current_verify_token(api_client, base_url, auth_headers)
        r = requests.get(
            f"{base_url}/api/whatsapp/webhook",
            params={"hub.mode": "subscribe", "hub.verify_token": vt, "hub.challenge": "abc"},
            timeout=15,
        )
        assert r.status_code == 200, r.text
        assert r.text == "abc"

    def test_webhook_verify_wrong_token_403(self, base_url):
        r = requests.get(
            f"{base_url}/api/whatsapp/webhook",
            params={"hub.mode": "subscribe", "hub.verify_token": "wrong", "hub.challenge": "abc"},
            timeout=15,
        )
        assert r.status_code == 403


# ---------- Webhook POST signature validation ----------

class TestWebhookSignature:
    def test_post_webhook_bad_signature_403(self, base_url):
        body = json.dumps({"entry": []}).encode()
        r = requests.post(
            f"{base_url}/api/whatsapp/webhook",
            data=body,
            headers={"X-Hub-Signature-256": "sha256=deadbeef", "Content-Type": "application/json"},
            timeout=15,
        )
        assert r.status_code == 403

    def test_post_webhook_correct_signature_200(self, base_url):
        raw_obj = {
            "entry": [
                {
                    "changes": [
                        {
                            "value": {
                                "contacts": [{"profile": {"name": "Alice"}}],
                                "messages": [
                                    {
                                        "id": f"wamid.test-{int(time.time()*1000)}",
                                        "from": "15551119999",
                                        "type": "text",
                                        "text": {"body": "Hi"},
                                    }
                                ],
                            }
                        }
                    ]
                }
            ]
        }
        raw = json.dumps(raw_obj).encode()
        sig = "sha256=" + hmac.new(FAKE_APP_SECRET.encode(), raw, hashlib.sha256).hexdigest()
        r = requests.post(
            f"{base_url}/api/whatsapp/webhook",
            data=raw,
            headers={"X-Hub-Signature-256": sig, "Content-Type": "application/json"},
            timeout=30,
        )
        assert r.status_code == 200, r.text
        assert r.json() == {"ok": True}


# ---------- Simulator dispatch payload ----------

class TestSimulatorAutoDispatch:
    def _run_flow(self, api_client, base_url):
        # Hi
        r = api_client.post(f"{base_url}/api/whatsapp/message", json={
            "customer_name": "Alice", "customer_phone": "+15551112222", "message": "Hi"
        }, timeout=20)
        assert r.status_code == 200, r.text
        sid = r.json()["session_id"]

        # Grab an item id
        menu = api_client.get(f"{base_url}/api/menu", timeout=15).json()
        assert menu, "seed menu should exist"
        item_id = menu[0]["id"]

        # add:<id>
        r = api_client.post(f"{base_url}/api/whatsapp/message", json={
            "session_id": sid, "message": f"add:{item_id}"
        }, timeout=20)
        assert r.status_code == 200

        # checkout
        r = api_client.post(f"{base_url}/api/whatsapp/message", json={
            "session_id": sid, "message": "checkout"
        }, timeout=20)
        assert r.status_code == 200

        # yes -> confirm
        r = api_client.post(f"{base_url}/api/whatsapp/message", json={
            "session_id": sid, "message": "yes"
        }, timeout=30)
        assert r.status_code == 200, r.text
        return r.json()

    def test_dispatch_with_wa_enabled_but_fake_creds(self, api_client, base_url, auth_headers):
        # Ensure enabled + fake creds saved (previous test class did this, but be defensive)
        api_client.patch(f"{base_url}/api/settings", json={
            "whatsapp_enabled": True,
            "whatsapp_access_token": FAKE_TOKEN,
            "whatsapp_phone_number_id": FAKE_PHONE_ID,
            "whatsapp_app_secret": FAKE_APP_SECRET,
            "owner_whatsapp_number": FAKE_OWNER,
        }, headers=auth_headers, timeout=15)

        data = self._run_flow(api_client, base_url)
        replies = data["replies"]
        confirm = replies[-1]
        wa = confirm["payload"].get("whatsapp_dispatch")
        assert wa is not None, "confirm reply must carry whatsapp_dispatch"
        assert "customer" in wa and "owner" in wa
        # Meta will reject fake token → delivered False (or simulator True); must not crash
        assert wa["customer"]["delivered"] is False
        assert wa["owner"]["delivered"] is False

    def test_dispatch_when_disabled_falls_back_to_simulator(self, api_client, base_url, auth_headers):
        # Disable WA
        api_client.patch(f"{base_url}/api/settings", json={"whatsapp_enabled": False},
                         headers=auth_headers, timeout=15)
        data = self._run_flow(api_client, base_url)
        wa = data["replies"][-1]["payload"].get("whatsapp_dispatch")
        assert wa is not None
        assert wa["customer"]["delivered"] is False
        assert wa["customer"].get("simulator") is True
        assert wa["owner"]["delivered"] is False
        assert wa["owner"].get("simulator") is True

        # Re-enable so following tests see enabled state (housekeeping)
        api_client.patch(f"{base_url}/api/settings", json={"whatsapp_enabled": True},
                         headers=auth_headers, timeout=15)


